# Shell helpers for the docs tasks. Source with: . "$(dirname "$0")/.helpers.sh"
#
# Every tasks.md under docs/ is generated from the tasks themselves (mise's own task list):
#   docs/tasks.md              the phases and the docs tasks (the ones not tied to a Worker)
#   docs/<component>/tasks.md  one per folder in mise-tasks/, so a new component gets one automatically

# The components: every folder in mise-tasks/ except docs, which docs/tasks.md covers.
doc_components() { find mise-tasks -mindepth 1 -maxdepth 1 -type d ! -name docs -exec basename {} \; | sort; }

# Prints the generated tasks.md for one target: "root" (phases and docs) or a component name.
doc_page() {
  local target=$1 title
  if [ "$target" = root ]; then title="Phases and docs tasks"; else title="$target tasks"; fi
  printf '# %s\n\nGenerated by `mise run docs:build` from the tasks themselves. Don'"'"'t edit: `docs:test` fails when this is out of date.\nChange a task'"'"'s `#MISE description` (or a phase'"'"'s description in mise.toml) instead.\n\nEach task shows its flags and arguments. "(listed)" means `mise tasks` shows it. "Runs first" is what it runs before itself; for a phase, its steps in order.\n\n' "$title"
  # Each task's usage line (its flags and arguments), from its #USAGE spec.
  local usages
  usages=$(for name in $(mise tasks --hidden --json | jq -r '.[].name'); do
    mise tasks info "$name" --json | jq -c --arg n "$name" '{($n): ((.usage_spec // "{}") | (if type == "string" then fromjson else . end) | .cmd.usage // "")}'
  done | jq -s 'add')
  mise tasks --hidden --json | jq -r --arg root "$PWD/" --arg target "$target" --argjson usages "$usages" '
    def group: if (.name | test("^[0-9]")) then "phases" else (.name | split(":") | .[:-1] | join(":")) end;
    def wanted: if $target == "root" then (. == "phases" or . == "docs") else (. == $target or startswith($target + ":")) end;
    def code: "`" + . + "`";
    map(. + {group: group}) | map(select(.group | wanted))
    | group_by(.group) | sort_by(if .[0].group == "phases" then "0" else "1" + .[0].group end)
    | map(
        "## " + .[0].group + "\n\n| Task | What it does | Runs first | Timeout | File |\n|---|---|---|---|---|\n" +
        (sort_by(.name) | map(
          "| " + ((.name + (if ($usages[.name] // "") != "" then " " + $usages[.name] else "" end)) | code) + (if .hide then "" else " (listed)" end) +
          " | " + (.description | gsub("\\|"; "\\|")) +
          " | " + ((((.run // []) | map(objects | .task)) + (.depends // [])) | map(code) | join(", ")) +
          " | " + (.timeout // "") +
          " | " + (if (.source // "") | startswith($root) then (.source | ltrimstr($root) | code) else "mise.toml" end) + " |"
        ) | join("\n"))
      )
    | join("\n\n")'
}

# Path of the generated tasks.md for a target.
doc_path() { if [ "$1" = root ]; then echo docs/tasks.md; else echo "docs/$1/tasks.md"; fi; }
